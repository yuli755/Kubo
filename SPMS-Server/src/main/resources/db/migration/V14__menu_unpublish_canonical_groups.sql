-- ============================================================================
-- 菜单解除「发布态」：让被 V10 冻结的分组重新可见、可维护
-- ============================================================================
-- 背景（2026-09-29 前后端联调 + 浏览器实测）：
--   V10__menu_canonical_paths.sql 以 is_published = 1 种下 4 条菜单：
--     172 工厂与库位 / 173 人员组织 / 175 数据权限 / 174 操作日志
--   而 BaseEntity.isPublished 的 Java 侧默认值是 false，筛选体一反序列化就带着它，
--   BaseService.buildPredicates 于是给每一次 POST /menu/getList 隐式加上 is_published = 0：
--     * 这 4 条菜单不在响应里；
--     * 它们的子菜单因父节点缺失，被 Trees.buildTreeList 连带丢弃；
--     * 前端路由是**按返回的菜单**动态注册的（appRouter.initVueRouter），菜单不返回
--       → 路由不注册 → 直连地址落到 catch-all 的 404 页。
--   净效果：仓库管理 / 库位结构 / 用户管理 / 角色管理 / 部门管理 / 操作日志 /
--   数据资源 / 行级策略 / 列级脱敏 —— 9 个页面在界面上彻底不可达，
--   其中包含整个「人员组织」与整个「数据权限」管理台。
--   同期后端 911 个测试、前端 778 个测试全绿，浏览器控制台 0 报错。
--
-- 两处必须一起修，缺一处都还会复发：
--   1) 代码侧（根因）：BaseEntity.isPublished 标 @FilterIgnore，发布态不再参与默认筛选。
--      只修数据不修代码，任何人在菜单管理里「发布」一条菜单，它就会连同子树再次消失。
--   2) 数据侧（本脚本）：把菜单的 is_published 归零。菜单是配置项不是业务单据，
--      「发布 = 冻结（拒改拒删）」对它没有意义 —— 冻结的后果是菜单管理页面对这 4 条
--      只能看不能改，而它本该是维护菜单的入口。菜单的可见性开关是 is_disabled。
--
-- 刻意不动 tenant：唯一的平台默认租户带 is_published = 1 属于**保护性冻结**
--   （拒改拒删正是想要的效果），且没有任何列表查询依赖它，改它只会削弱保护。
--
-- 幂等：UPDATE ... WHERE is_published = 1；重复执行无副作用（CI 连跑两遍判据）。
-- ============================================================================
UPDATE `menu` SET `is_published` = 0 WHERE `is_published` = 1;
