-- H2 Test Schema for Data Permission Entities
-- Using H2-compatible syntax

-- data_resource
CREATE TABLE IF NOT EXISTS data_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    owner_columns VARCHAR(512),
    resource_key VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL,
    supported_actions VARCHAR(256) NOT NULL,
    table_alias VARCHAR(64),
    table_name VARCHAR(128) NOT NULL,
    tenant_column VARCHAR(64) NOT NULL,
    filterable_columns VARCHAR(512),
    version_no BIGINT NOT NULL,
    CONSTRAINT uk_data_resource_key UNIQUE (resource_key)
);

-- data_permission_orm_parity_log（两套 ORM 行数对账；与 docs/database/migration/20260908_*.sql 对齐）
