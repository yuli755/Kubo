-- H2 Test Schema for Data Permission Entities
-- Using H2-compatible syntax

-- data_resource
CREATE TABLE IF NOT EXISTS data_resource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    owner_columns VARCHAR(512),
    resource_key VARCHAR(128) NOT NULL,
    status VARCHAR(16) NOT NULL,
    supported_actions VARCHAR(256) NOT NULL,
    table_alias VARCHAR(64),
    table_name VARCHAR(128) NOT NULL,
    tenant_column VARCHAR(64) NOT NULL,
    filterable_columns VARCHAR(512),
    version_no BIGINT NOT NULL,
    CONSTRAINT uk_data_resource_key UNIQUE (resource_key)
);

-- permission（PermissionSystemSeedTest 验证系统特权身份播种；与 dev 库 permission 表对齐）
CREATE TABLE IF NOT EXISTS permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    identity VARCHAR(255) DEFAULT '' UNIQUE,
    is_system BOOLEAN DEFAULT FALSE,
    type INT DEFAULT 0,
    name VARCHAR(255) DEFAULT '',
    parent_id BIGINT DEFAULT 0
);

-- data_permission_diff_log（影子比对差异；与 infra/init-sql/init.sql 对齐）
CREATE TABLE IF NOT EXISTS data_permission_diff_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    resource_key VARCHAR(128) NOT NULL,
    action_name VARCHAR(16) NOT NULL,
    trace_id VARCHAR(64),
    user_id BIGINT,
    tenant_id BIGINT,
    baseline_count BIGINT,
    guarded_count BIGINT,
    verdict VARCHAR(16) NOT NULL,
    cost_ms BIGINT,
    detail TEXT
);
CREATE INDEX IF NOT EXISTS idx_dp_diff_create_time ON data_permission_diff_log (create_time);

-- data_permission_deny_log（拒绝事件审计；与 docs/database/migration/20260908_data_permission_deny_log.sql 对齐）
CREATE TABLE IF NOT EXISTS data_permission_deny_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    resource_key VARCHAR(128) NOT NULL,
    reason VARCHAR(64) NOT NULL,
    mode VARCHAR(16) NOT NULL,
    user_id BIGINT,
    tenant_id BIGINT,
    detail TEXT
);
CREATE INDEX IF NOT EXISTS idx_dp_deny_create_time ON data_permission_deny_log (create_time);

-- data_policy
CREATE TABLE IF NOT EXISTS data_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    policy_code VARCHAR(128) NOT NULL,
    resource_id BIGINT NOT NULL,
    subject_type VARCHAR(16) NOT NULL,
    subject_id BIGINT,
    role_code VARCHAR(128),
    action_name VARCHAR(16) NOT NULL,
    condition_json CLOB NOT NULL DEFAULT '{}',
    priority INT DEFAULT 0 NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    version_no BIGINT NOT NULL,
    CONSTRAINT uk_data_policy_code UNIQUE (policy_code)
);

-- data_field_policy
CREATE TABLE IF NOT EXISTS data_field_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    resource_id BIGINT NOT NULL,
    field_name VARCHAR(128) NOT NULL,
    role_code VARCHAR(128) NOT NULL,
    action_name VARCHAR(16) NOT NULL,
    mask_type VARCHAR(32) NOT NULL,
    mask_expression VARCHAR(512),
    allow_plaintext BOOLEAN DEFAULT FALSE NOT NULL,
    priority INT DEFAULT 0 NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT uk_data_field_policy UNIQUE (resource_id, field_name, role_code)
);
-- permission_change_outbox（权限变更 Outbox；与 docs/database/migration/20260817_data_permission_model.sql 对齐）
CREATE TABLE IF NOT EXISTS permission_change_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    event_key VARCHAR(192) NOT NULL,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    retry_count INT DEFAULT 0 NOT NULL,
    next_retry_at BIGINT,
    processed_at BIGINT,
    last_error VARCHAR(2000),
    CONSTRAINT uk_permission_outbox_event UNIQUE (event_key)
);
CREATE INDEX IF NOT EXISTS idx_permission_outbox_dispatch ON permission_change_outbox (status, next_retry_at, id);

-- operation_log（通用操作审计；与 docs/database/migration/20260910_operation_log.sql 对齐）
CREATE TABLE IF NOT EXISTS operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_time BIGINT DEFAULT 0 NOT NULL,
    is_disabled BOOLEAN DEFAULT FALSE NOT NULL,
    update_time BIGINT DEFAULT 0 NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    resource_key VARCHAR(128) NOT NULL,
    action VARCHAR(32) NOT NULL,
    user_id BIGINT,
    tenant_id BIGINT,
    target_id BIGINT,
    target_label VARCHAR(255),
    before_snapshot TEXT,
    after_snapshot TEXT
);
CREATE INDEX IF NOT EXISTS idx_operation_log_create_time ON operation_log (create_time);
