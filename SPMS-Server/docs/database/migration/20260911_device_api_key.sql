-- ============================================================================
-- [T1] asset.device  ← DeviceEntity.java
-- A1 设备采集端认证（2026-09-11 拍板：三个 @Permission(login=false) 出口改用 API-Key）。
--
-- 背景：getCurrentReport / getDeviceConfig / getDevicePayloadHistory 三个采集端出口
-- 原仅按 IP 限流、无认证，任意方可按数字 id 或 uuid 枚举任意设备的实时数据与历史。
-- 现给 device 增加 api_key 列：新建设备自动生成（DeviceService.beforeAppSaveToDatabase），
-- 出口按 uuid/id 定位设备后常量时间比对（MessageDigest.isEqual，设备不存在与密钥
-- 不匹配返回同一 401）。密钥写端可入、读端永不回显（@JsonProperty(WRITE_ONLY)）。
--
-- 依赖：20260909 脚本先执行（kubo_mt_add_column 存储过程在其中定义）。过程幂等
--       （information_schema 先判存在性），本脚本可重复执行。device 表本身由
--       Hibernate ddl-auto 在业务库初始化阶段生成，本脚本只追加列；表不存在时
--       kubo_mt_add_column 静默跳过（与 tenant_id/creator_id 回填同口径）。
-- ============================================================================
CALL kubo_mt_add_column('device', 'api_key', 'api_key VARCHAR(255) NULL COMMENT ''采集端API密钥''');
