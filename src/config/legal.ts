/**
 * # 内置法律文本（隐私政策 / 服务条款）单一数据源
 *
 * ## 为什么存在
 * 登录页的《隐私政策》《服务条款》曾是指向 `/privacy`、`/terms` 的**死链**——点了被
 * 守卫弹回登录页，等于「点了等于没点」（§16.6 实测）。协议同意是登录的合规前置，
 * 而「同意一个读不到的文本」比不同意更糟，故补上真实可读的页面。
 *
 * ## 为什么内容放在这里而不是写进 legal.vue
 * 文案是**数据**：单独成模块才能被单测直接断言（章节非空、口径不退化），
 * 视图只做渲染。与 `config/palette.ts`（颜色单一数据源）是同一手法。
 *
 * ## 诚实边界
 * 这是通用内置版：只陈述本系统**实际会做什么**（账号/业务/日志数据、错误上报、
 * 邮箱验证码），不虚构承诺；正式部署对外时应由组织确认正式文本 —— 页面底部
 * 明示这一点，避免「内置文本被当成法务定稿」。
 */

